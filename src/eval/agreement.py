"""Live Claims inter-annotator agreement (ESE DoD: "every item double-labelled, Cohen's κ reported").

`python -m src.eval.agreement sheet`  -> writes the blind sheet data/live_claims/second_labeller_sheet.csv
                                         (id, claim, factcheck_url + empty label2/labeller/notes; no first label).
`python -m src.eval.agreement`        -> (`make agreement`) κ of the human sheet and of the AI-assisted pass
                                         (data/live_claims/second_pass_ai.csv) vs `label` -> docs/results/agreement.md.
Rows whose label2 is empty or UNREADABLE are excluded from κ; n is reported.
"""
from __future__ import annotations

import sys

import pandas as pd
from sklearn.metrics import cohen_kappa_score

from src.config import LIVE_CLAIMS_DIR, RESULTS_DIR, VERDICTS
from src.eval.live_claims import load_live_claims

SHEET = LIVE_CLAIMS_DIR / "second_labeller_sheet.csv"
AI_PASS = LIVE_CLAIMS_DIR / "second_pass_ai.csv"
OUT = RESULTS_DIR / "agreement.md"


def make_sheet(path=SHEET) -> None:
    d = load_live_claims()[["id", "claim", "factcheck_url"]].assign(label2="", labeller="", notes="")
    d.to_csv(path, index=False)


def agreement(gold: pd.DataFrame, second: pd.DataFrame) -> dict:
    """gold: id,label; second: id,label2. Returns n, excluded, kappa, raw agreement, confusion, per-class, disagreements."""
    s = second.assign(label2=second.label2.fillna("").astype(str).str.strip().str.upper())
    bad = set(s.label2) - set(VERDICTS) - {"", "UNREADABLE"}
    if bad:
        raise ValueError(f"label2 must be one of {VERDICTS} (or empty / UNREADABLE), got {bad}")
    m = gold[["id", "label"]].merge(s, on="id", how="inner")
    used = m[m.label2.isin(VERDICTS)]
    conf = pd.crosstab(pd.Categorical(used.label, VERDICTS), pd.Categorical(used.label2, VERDICTS),
                       rownames=["label (first)"], colnames=["label2 (second)"], dropna=False)
    # specific agreement per class: 2·n_cc / (row_c + col_c)
    per = {c: (2 * conf.loc[c, c] / (conf.loc[c].sum() + conf[c].sum())) if conf.loc[c].sum() + conf[c].sum() else float("nan")
           for c in VERDICTS}
    return {"n": len(used), "excluded": m.loc[~m.label2.isin(VERDICTS), "id"].tolist(),
            "kappa": cohen_kappa_score(used.label, used.label2, labels=VERDICTS) if len(used) else float("nan"),
            "raw": (used.label == used.label2).mean() if len(used) else float("nan"),
            "confusion": conf, "per_class": per, "disagree": used[used.label != used.label2]}


def section(r: dict) -> list[str]:
    conf = r["confusion"]
    L = [f"- n used = **{r['n']}**; excluded (empty/UNREADABLE) = {len(r['excluded'])}"
         + (f" ({', '.join(r['excluded'])})" if r["excluded"] else ""),
         f"- Cohen's κ = **{r['kappa']:.4f}**; raw agreement = {r['raw']:.4f}; disagreements = **{len(r['disagree'])}**", "",
         "Confusion (rows = first label, columns = second label):", "",
         "| | " + " | ".join(conf.columns) + " |", "|---" * (len(conf.columns) + 1) + "|"]
    L += [f"| **{i}** | " + " | ".join(str(v) for v in row) + " |" for i, row in conf.iterrows()]
    L += ["", "Per-class specific agreement 2·n_cc / (row + col):", "", "| class | agreement |", "|---|---|"]
    L += [f"| {c} | {v:.3f} |" for c, v in r["per_class"].items()]
    return L


def main() -> None:
    gold = load_live_claims()
    md = ["# Live Claims Set — inter-annotator agreement", "",
          "Generated by `make agreement` (`src/eval/agreement.py`). First label = `label` in "
          "`data/live_claims/live_claims.csv` (fact-checker rating mapped per `data/live_claims/README.md`).", "",
          "## Human second labeller", ""]
    h = pd.read_csv(SHEET, dtype=str, keep_default_na=False) if SHEET.exists() else None
    if h is None or not h.label2.str.strip().ne("").any():
        md += ["Not filled yet: `data/live_claims/second_labeller_sheet.csv` has no `label2` values. "
               "**The ESE double-labelling DoD is not met until a team member fills it.**"]
    else:
        md += [f"Labeller(s): {', '.join(sorted(set(h.labeller) - {''})) or 'unnamed'}", ""] + section(agreement(gold, h))
    if AI_PASS.exists():
        r = agreement(gold, pd.read_csv(AI_PASS, dtype=str, keep_default_na=False))
        ai = pd.read_csv(AI_PASS, dtype=str, keep_default_na=False).set_index("id")
        md += ["", "## AI-assisted second pass (NOT a human annotator)", "",
               "Source: `data/live_claims/second_pass_ai.csv`. Claude sub-agents re-opened each fact-check URL, "
               "were given only id / claim / URL (never `label` or `original_rating`), read the verdict on the page and "
               "mapped it with the README rules. **This is not an independent human annotator and does not satisfy the "
               "ESE DoD \"every item double-labelled\"**; it mostly checks that the label column still matches the live "
               "pages and that the mapping is applied consistently.", "",
               "Caveats: κ is expected to be high because both passes map the same published rating with the same "
               "rules; the only room for disagreement is unrated articles and the UNVERIFIABLE-vs-FAKE judgement. "
               "Snopes refuses the web-fetch tool (HTTP 402), so its pages were downloaded with curl and the rating read "
               "from the page's `reviewRating` (the same field the first pass used). Some `evidence_quote`s are the "
               "page's meta description or a fetch-tool summary rather than a verbatim body sentence; quotes over 20 "
               "words are cut with \"…\". Pass run 2026-11-12.", ""] + section(r)
        md += ["", "Disagreements (for team adjudication; `live_claims.csv` was not changed):", "",
               "| id | label | label2 (AI) | rating read | quote |", "|---|---|---|---|---|"]
        md += [f"| {d.id} | {d.label} | {d.label2} | {ai.loc[d.id, 'rating_read']} | {ai.loc[d.id, 'evidence_quote']} |"
               for d in r["disagree"].itertuples()] or ["| — | | | | |"]
    OUT.write_text("\n".join(md) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    make_sheet() if sys.argv[1:] == ["sheet"] else main()
